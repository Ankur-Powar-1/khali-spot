import { act, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import { App } from './App'
import { fixtureLot, fixtureSlots, testApi } from './test-api'

describe('owner and visitor experiences', () => {
  it('signs in and restores an existing session on remount', async () => {
    const user = userEvent.setup()
    const fixture = testApi('owner', false)
    const view = render(<App api={fixture.api} />)
    await user.type(await screen.findByLabelText('Email address'), 'owner@example.test')
    await user.type(screen.getByLabelText('Password'), 'password123')
    await user.click(within(screen.getByRole('form', { name: 'Authentication' })).getByRole('button', { name: /^Sign in$/ }))
    expect(await screen.findByText('Your lots. Your control.')).toBeVisible()
    expect(fixture.api.signIn).toHaveBeenCalledWith('owner@example.test', 'password123')
    view.unmount()
    const restored = testApi()
    render(<App api={restored.api} />)
    expect(await screen.findByRole('heading', { name: 'Library parking' })).toBeVisible()
    expect(restored.api.session).toHaveBeenCalled()
  })
  it('creates an owner account and explains confirmation without pretending login succeeded', async () => {
    const user = userEvent.setup()
    const { api } = testApi('owner', false)
    render(<App api={api} />)
    await user.click(await screen.findByRole('button', { name: 'Create account' }))
    await user.click(screen.getByRole('radio', { name: /Lot owner/ }))
    await user.type(screen.getByLabelText('Email address'), 'owner@example.test')
    await user.type(screen.getByLabelText('Password'), 'password123')
    await user.click(within(screen.getByRole('form', { name: 'Authentication' })).getByRole('button', { name: /^Create account$/ }))
    expect(await screen.findByText(/Check your email to confirm/)).toBeVisible()
    expect(api.signUp).toHaveBeenCalledWith('owner@example.test', 'password123', 'owner')
    expect(screen.queryByText('Your lots. Your control.')).not.toBeInTheDocument()
  })
  it('previews 2x5, saves a draft, publishes, and marks the stable slot ID', async () => {
    const user = userEvent.setup()
    const { api } = testApi()
    render(<App api={api} />)
    await user.click(await screen.findByRole('button', { name: 'Create parking lot' }))
    await user.type(screen.getByLabelText('Lot name'), 'Science block')
    await user.type(screen.getByLabelText('Address'), 'East gate')
    await user.click(screen.getByRole('button', { name: 'Preview layout' }))
    expect(screen.getByText('A1')).toBeVisible()
    expect(screen.getByText('B5')).toBeVisible()
    expect(api.createLot).not.toHaveBeenCalled()
    await user.click(screen.getByRole('button', { name: 'Save draft lot' }))
    expect(await screen.findByRole('button', { name: 'Publish lot' })).toBeVisible()
    await user.click(screen.getByRole('button', { name: 'Publish lot' }))
    expect(await screen.findByRole('button', { name: 'Unpublish lot' })).toBeVisible()
    await user.click(screen.getByRole('button', { name: 'A1: unknown' }))
    await user.click(screen.getByRole('button', { name: 'Mark occupied' }))
    expect(await screen.findByRole('button', { name: 'A1: occupied' })).toBeVisible()
    expect(api.setSlot).toHaveBeenCalledWith('slot-0', 'occupied')
  })
  it('invalidates preview when dimensions change and never saves the stale preview', async () => {
    const user = userEvent.setup()
    const { api } = testApi()
    render(<App api={api} />)
    await user.click(await screen.findByRole('button', { name: 'Create parking lot' }))
    await user.type(screen.getByLabelText('Lot name'), 'Lot')
    await user.type(screen.getByLabelText('Address'), 'Gate')
    await user.click(screen.getByRole('button', { name: 'Preview layout' }))
    await user.clear(screen.getByLabelText('Number of rows'))
    await user.type(screen.getByLabelText('Number of rows'), '3')
    expect(screen.queryByRole('button', { name: 'Save draft lot' })).not.toBeInTheDocument()
    expect(api.createLot).not.toHaveBeenCalled()
    await user.click(screen.getByRole('button', { name: 'Preview layout' }))
    expect(screen.getByText('C5')).toBeVisible()
  })
  it('limits owners to their own lots and never exposes manual controls for sensor slots', async () => {
    const user = userEvent.setup()
    const fixture = testApi()
    fixture.changeLots([fixtureLot, { ...fixtureLot, id: 'another', owner_id: 'other', name: 'Other owner' }])
    fixture.changeSlots(fixtureSlots.map((s) => s.id === 'slot-0' ? { ...s, input_mode: 'sensor', input_source: 'future_sensor' } : s))
    render(<App api={fixture.api} />)
    await user.click(await screen.findByRole('button', { name: /Library parking/ }))
    expect(screen.queryByText('Other owner')).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'A1: free' })).not.toBeInTheDocument()
    expect(screen.getByLabelText('A1: free')).toBeVisible()
  })
  it('renders read-only visitor maps, updates after realtime invalidation, and removes unpublished lots', async () => {
    const user = userEvent.setup()
    const fixture = testApi('visitor')
    render(<App api={fixture.api} />)
    await user.click(await screen.findByRole('button', { name: /Library parking/ }))
    expect(screen.queryByRole('button', { name: /Publish lot|Edit details|A1: free/ })).not.toBeInTheDocument()
    expect(screen.getByLabelText('A1: free')).toBeVisible()
    act(() => fixture.changeSlots(fixtureSlots.map((slot) => ({ ...slot, occupancy: 'occupied' }))))
    expect(await screen.findByLabelText('A1: occupied')).toBeVisible()
    act(() => fixture.changeLots([{ ...fixtureLot, published: false }]))
    expect(await screen.findByText('No published lots just yet.')).toBeVisible()
    expect(screen.queryByLabelText('A1: occupied')).not.toBeInTheDocument()
  })
  it('has an informational Pay & Park tab with no payment or booking effects', async () => {
    const user = userEvent.setup()
    const { api } = testApi('visitor')
    render(<App api={api} />)
    await user.click(await screen.findByRole('button', { name: /Pay & Park/ }))
    expect(screen.getByText('Coming soon')).toBeVisible()
    expect(screen.getByText(/No payments or reservations are available/)).toBeVisible()
    expect(screen.queryByRole('textbox')).not.toBeInTheDocument()
    expect(api.setSlot).not.toHaveBeenCalled()
    expect(api.createLot).not.toHaveBeenCalled()
  })
  it('shows disconnected last-known data and blocks owner changes', async () => {
    const user = userEvent.setup()
    const fixture = testApi()
    render(<App api={fixture.api} />)
    await user.click(await screen.findByRole('button', { name: /Library parking/ }))
    act(() => fixture.disconnect())
    expect(screen.getByText(/Not live/)).toBeVisible()
    expect(screen.getByRole('button', { name: 'A1: free' })).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Mark all free' })).toBeDisabled()
    expect(screen.getByText(/These are last-known values/)).toBeVisible()
    act(() => fixture.reconnect())
    await waitFor(() => expect(screen.getByRole('button', { name: 'A1: free' })).toBeEnabled())
  })
  it('surfaces backend failures without presenting an empty successful lot list', async () => {
    const fixture = testApi()
    vi.mocked(fixture.api.snapshot).mockRejectedValue(new Error('Schema missing'))
    render(<App api={fixture.api} />)
    expect(await screen.findByRole('alert')).toHaveTextContent('Schema missing')
    expect(screen.queryByText('Your first lot starts here.')).not.toBeInTheDocument()
  })
  it('keeps the previous occupancy when the backend rejects a write', async () => {
    const user = userEvent.setup()
    const fixture = testApi()
    vi.mocked(fixture.api.setSlot).mockRejectedValue(new Error('Not owned'))
    render(<App api={fixture.api} />)
    await user.click(await screen.findByRole('button', { name: /Library parking/ }))
    await user.click(screen.getByRole('button', { name: 'A1: free' }))
    await user.click(screen.getByRole('button', { name: 'Mark occupied' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Not owned')
    expect(screen.getByRole('button', { name: 'A1: free' })).toBeVisible()
    expect(screen.getByRole('dialog', { name: 'Update A1' })).toBeVisible()
  })
  it('opens slot controls, switches selection, and dismisses without writing', async () => {
    const user = userEvent.setup()
    const fixture = testApi()
    render(<App api={fixture.api} />)
    await user.click(await screen.findByRole('button', { name: /Library parking/ }))
    const first = screen.getByRole('button', { name: 'A1: free' })
    await user.click(first)
    expect(screen.getByRole('dialog', { name: 'Update A1' })).toBeVisible()
    expect(first).toHaveAttribute('aria-expanded', 'true')
    await user.click(screen.getByRole('button', { name: 'A2: occupied' }))
    expect(screen.queryByRole('dialog', { name: 'Update A1' })).not.toBeInTheDocument()
    expect(screen.getByRole('dialog', { name: 'Update A2' })).toBeVisible()
    await user.keyboard('{Escape}')
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'A2: occupied' })).toHaveFocus()
    await user.click(first)
    await user.click(screen.getByRole('heading', { name: 'Parking layout' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    await user.click(first)
    await user.click(screen.getByRole('button', { name: 'Close slot update' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(first).toHaveFocus()
    expect(fixture.api.setSlot).not.toHaveBeenCalled()
  })
  it('blocks an open popup when disconnected and removes it for a sensor-mode slot', async () => {
    const user = userEvent.setup()
    const fixture = testApi()
    render(<App api={fixture.api} />)
    await user.click(await screen.findByRole('button', { name: /Library parking/ }))
    await user.click(screen.getByRole('button', { name: 'A1: free' }))
    act(() => fixture.disconnect())
    const popup = screen.getByRole('dialog', { name: 'Update A1' })
    expect(within(popup).getByRole('button', { name: 'Mark occupied' })).toBeDisabled()
    act(() => fixture.changeSlots(fixtureSlots.map((slot) => slot.id === 'slot-0'
      ? { ...slot, input_mode: 'sensor', input_source: 'future_sensor' } : slot)))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    expect(fixture.api.setSlot).not.toHaveBeenCalled()
  })
  it('saves lot detail changes without rebuilding slots', async () => {
    const user = userEvent.setup()
    const fixture = testApi()
    render(<App api={fixture.api} />)
    await user.click(await screen.findByRole('button', { name: /Library parking/ }))
    await user.click(screen.getByRole('button', { name: 'Edit details' }))
    const name = screen.getByLabelText('Lot name')
    await user.clear(name); await user.type(name, 'New library')
    await user.click(screen.getByRole('button', { name: 'Save details' }))
    expect(await screen.findByRole('heading', { name: 'New library' })).toBeVisible()
    expect(fixture.api.updateLot).toHaveBeenCalledWith('lot-1', 'New library', fixtureLot.address, fixtureLot.description)
    expect(fixture.api.createLot).not.toHaveBeenCalled()
  })
  it('clears private owner data on logout', async () => {
    const user = userEvent.setup()
    const fixture = testApi()
    render(<App api={fixture.api} />)
    await screen.findByRole('heading', { name: 'Library parking' })
    await user.click(screen.getByRole('button', { name: 'Sign out' }))
    const form = await screen.findByRole('form', { name: 'Authentication' })
    expect(form).toBeVisible()
    expect(screen.queryByRole('heading', { name: 'Library parking' })).not.toBeInTheDocument()
    expect(within(screen.getByRole('banner')).queryByRole('button', { name: 'Sign out' })).not.toBeInTheDocument()
  })
  it('confirms a current-lot bulk update and leaves sensor spaces unchanged', async () => {
    const user = userEvent.setup()
    const fixture = testApi()
    fixture.changeSlots(fixtureSlots.map((s) => s.id === 'slot-1'
      ? { ...s, input_mode: 'sensor', input_source: 'future_sensor' } : s))
    const confirm = vi.spyOn(window, 'confirm').mockReturnValue(true)
    render(<App api={fixture.api} />)
    await user.click(await screen.findByRole('button', { name: /Library parking/ }))
    await user.click(screen.getByRole('button', { name: 'Mark all free' }))
    expect(confirm).toHaveBeenCalledWith(expect.stringContaining('all 9 manual-input spaces'))
    expect(fixture.api.markAllFree).toHaveBeenCalledWith(fixtureLot.id)
    expect(await screen.findByRole('button', { name: 'B5: free' })).toBeVisible()
    expect(screen.getByLabelText('A2: occupied')).toBeVisible()
  })
  it('does not write when bulk confirmation is cancelled', async () => {
    const user = userEvent.setup()
    const fixture = testApi()
    vi.spyOn(window, 'confirm').mockReturnValue(false)
    render(<App api={fixture.api} />)
    await user.click(await screen.findByRole('button', { name: /Library parking/ }))
    await user.click(screen.getByRole('button', { name: 'Mark all free' }))
    expect(fixture.api.markAllFree).not.toHaveBeenCalled()
    expect(screen.getByRole('button', { name: 'A2: occupied' })).toBeVisible()
  })
  it('hides bulk controls for visitors and disables sensor-only lots', async () => {
    const user = userEvent.setup()
    const visitor = testApi('visitor')
    const view = render(<App api={visitor.api} />)
    await user.click(await screen.findByRole('button', { name: /Library parking/ }))
    expect(screen.queryByRole('button', { name: 'Mark all free' })).not.toBeInTheDocument()
    view.unmount()
    const owner = testApi()
    owner.changeSlots(fixtureSlots.map((s) => ({ ...s, input_mode: 'sensor', input_source: 'future_sensor' })))
    render(<App api={owner.api} />)
    await user.click(await screen.findByRole('button', { name: /Library parking/ }))
    expect(screen.getByRole('button', { name: 'Mark all free' })).toBeDisabled()
  })
  it('surfaces a bulk failure without changing previous occupancy', async () => {
    const user = userEvent.setup()
    const fixture = testApi()
    vi.spyOn(window, 'confirm').mockReturnValue(true)
    vi.mocked(fixture.api.markAllFree).mockRejectedValue(new Error('Bulk action needs database setup'))
    render(<App api={fixture.api} />)
    await user.click(await screen.findByRole('button', { name: /Library parking/ }))
    await user.click(screen.getByRole('button', { name: 'Mark all free' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Bulk action needs database setup')
    expect(screen.getByRole('button', { name: 'A2: occupied' })).toBeVisible()
    expect(screen.getByRole('button', { name: 'B5: unknown' })).toBeVisible()
  })
})
